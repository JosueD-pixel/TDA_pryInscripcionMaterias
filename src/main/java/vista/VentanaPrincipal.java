    /** Crea un alumno con los datos del formulario. */
    private void registrarAlumno() {
        try {
            String matricula = txtMatricula.getText().trim();
            if (buscarAlumno(matricula) != null) {
                mostrarAviso("Ya existe un alumno con la matricula " + matricula);
                return;
            }
            double saldo = leerNumero(txtSaldo.getText(), "saldo inicial");
            // el constructor de Alumno (y el de Persona) validan los datos
            Alumno nuevo = new Alumno(txtNombre.getText().trim(), matricula, saldo);
            alumnos.add(nuevo);

            txtNombre.setText("");
            txtMatricula.setText("");
            txtSaldo.setText("");
            txtNombre.requestFocus();
            actualizarTodo();
        } catch (IllegalArgumentException e) {
            mostrarAviso(e.getMessage());
        }
    }

    /** Deposita dinero al alumno seleccionado en la tabla. */
    private void depositar() {
        int fila = tablaAlumnos.getSelectedRow();
        if (fila == -1) {
            mostrarAviso("Selecciona un alumno en la tabla");
            return;
        }
        try {
            double monto = leerNumero(txtMonto.getText(), "monto");
            alumnos.get(fila).depositar(monto);
            txtMonto.setText("");
            actualizarTodo();
            tablaAlumnos.setRowSelectionInterval(fila, fila);
        } catch (IllegalArgumentException e) {
            mostrarAviso(e.getMessage());
        }
    }

    // =====================================================================
    //  MATERIAS
    // =====================================================================

    /** Crea una materia con los datos del formulario. */
    private void registrarMateria() {
        try {
            String nombre = txtNombreMateria.getText().trim();
            if (buscarMateria(nombre) != null) {
                mostrarAviso("Ya existe la materia " + nombre);
                return;
            }
            double costo = leerNumero(txtCosto.getText(), "costo");
            materias.add(new Materia(nombre, costo));

            txtNombreMateria.setText("");
            txtCosto.setText("");
            txtNombreMateria.requestFocus();
            actualizarTodo();
        } catch (IllegalArgumentException e) {
            mostrarAviso(e.getMessage());
        }
    }

    /** Regresa la materia seleccionada en la tabla, o null si no hay. */
    private Materia materiaSeleccionada() {
        int fila = tablaMaterias.getSelectedRow();
        if (fila == -1) {
            mostrarAviso("Selecciona una materia en la tabla");
            return null;
        }
        return materias.get(fila);
    }

    /** Cambia el costo de la materia seleccionada. */
    private void cambiarCosto() {
        Materia m = materiaSeleccionada();
        if (m == null) return;
        try {
            m.cambiarCosto(leerNumero(txtNuevoCosto.getText(), "nuevo costo"));
            txtNuevoCosto.setText("");
            int fila = tablaMaterias.getSelectedRow();
            actualizarTodo();
            tablaMaterias.setRowSelectionInterval(fila, fila);
        } catch (IllegalArgumentException e) {
            mostrarAviso(e.getMessage());
        }
    }

    /** Aplica un descuento a la materia seleccionada. */
    private void aplicarDescuento() {
        Materia m = materiaSeleccionada();
        if (m == null) return;
        try {
            m.aplicarDescuento(leerNumero(txtDescuento.getText(), "descuento"));
            txtDescuento.setText("");
            int fila = tablaMaterias.getSelectedRow();
            actualizarTodo();
            tablaMaterias.setRowSelectionInterval(fila, fila);
        } catch (IllegalArgumentException e) {
            mostrarAviso(e.getMessage());
        }
    }

    // =====================================================================
    //  INSCRIPCION
    // =====================================================================

    /** Inscribe al alumno seleccionado en la materia seleccionada. */
    private void inscribir() {
        Alumno a = (Alumno) cmbAlumno.getSelectedItem();
        Materia m = (Materia) cmbMateria.getSelectedItem();
        if (a == null) {
            mostrarAviso("Primero registra un alumno");
            return;
        }
        try {
            a.inscribirse(m);
            JOptionPane.showMessageDialog(this, "Inscripcion exitosa a " + m.getNombre(),
                    "Listo", JOptionPane.INFORMATION_MESSAGE);
            actualizarTodo();
        } catch (IllegalArgumentException | IllegalStateException e) {
            mostrarAviso(e.getMessage());
        }
    }

    /** Muestra en el area de texto los datos del alumno seleccionado. */
    private void mostrarDatosAlumno() {
        Alumno a = (Alumno) cmbAlumno.getSelectedItem();
        if (a == null) {
            txtDatos.setText("");
        } else {
            txtDatos.setText(a.mostrarDatos());
        }
    }

    // =====================================================================
    //  ACTUALIZAR TABLAS Y COMBOS
    // =====================================================================
    private void actualizarTodo() {
        if (!listo) return;

        // tabla de alumnos
        DefaultTableModel modeloA = (DefaultTableModel) tablaAlumnos.getModel();
        modeloA.setRowCount(0);
        for (Alumno a : alumnos) {
            modeloA.addRow(new Object[]{
                a.getMatricula(),
                a.getNombre(),
                String.format("$%.2f", a.consultarSaldo()),
                a.getNumMaterias() + "/" + Alumno.MAX_MATERIAS,
                String.format("$%.2f", a.calcularTotalMaterias(0))
            });
        }

        // tabla de materias
        DefaultTableModel modeloM = (DefaultTableModel) tablaMaterias.getModel();
        modeloM.setRowCount(0);
        for (Materia m : materias) {
            modeloM.addRow(new Object[]{m.getNombre(), String.format("$%.2f", m.getCosto())});
        }

        // combos de la pestaña Inscripcion (se conserva lo que estaba seleccionado)
        listo = false;
        Object alumnoSel = cmbAlumno.getSelectedItem();
        Object materiaSel = cmbMateria.getSelectedItem();
        cmbAlumno.setModel(new DefaultComboBoxModel<>(alumnos.toArray(new Alumno[0])));
        cmbMateria.setModel(new DefaultComboBoxModel<>(materias.toArray(new Materia[0])));
        if (alumnoSel != null) cmbAlumno.setSelectedItem(alumnoSel);
        if (materiaSel != null) cmbMateria.setSelectedItem(materiaSel);
        listo = true;

        mostrarDatosAlumno();
    }

    // =====================================================================
    //  UTILIDADES
    // =====================================================================
    private Alumno buscarAlumno(String matricula) {
        for (Alumno a : alumnos) {
            if (a.getMatricula().equalsIgnoreCase(matricula)) return a;
        }
        return null;
    }

    private Materia buscarMateria(String nombre) {
        for (Materia m : materias) {
            if (m.getNombre().equalsIgnoreCase(nombre)) return m;
        }
        return null;
    }

    /** Convierte el texto a numero; si no se puede, lanza una excepcion con mensaje claro. */
    private double leerNumero(String texto, String campo) {
        try {
            return Double.parseDouble(texto.trim());
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException("Escribe un numero valido en " + campo);
        }
    }

    private void mostrarAviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Aviso", JOptionPane.WARNING_MESSAGE);
    }

